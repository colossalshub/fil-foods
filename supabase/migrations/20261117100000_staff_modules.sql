create or replace function public.request_health_condition_removal(p_condition text, p_reason text default null)
returns public.health_condition_removal_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.health_condition_removal_requests;
  v_profile public.profiles;
  v_name text;
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;
  select * into v_profile from public.profiles where id = auth.uid() and role = 'client';
  if not found then raise exception 'not_authorized'; end if;
  if not exists (
    select 1 from public.client_health_items
    where client_id = auth.uid() and item_type = 'condition' and lower(value) = lower(trim(p_condition))
  ) then raise exception 'condition_not_found'; end if;
  select * into v_request from public.health_condition_removal_requests
  where client_id = auth.uid() and lower(condition) = lower(trim(p_condition)) and status = 'pending';
  if found then return v_request; end if;
  insert into public.health_condition_removal_requests (client_id, meal_recipient_id, condition, reason, requested_by)
  values (auth.uid(), v_profile.meal_recipient_id, trim(p_condition), nullif(trim(coalesce(p_reason, '')), ''), auth.uid())
  returning * into v_request;
  select trim(coalesce(r.first_name, v_profile.first_name) || ' ' || coalesce(r.last_name, v_profile.last_name))
    into v_name from (select 1) x left join public.meal_recipients r on r.id = v_profile.meal_recipient_id;
  perform public.notify_staff('dietitian_staff', 'removalRequest',
    'Condition removal request', v_name || ' · ' || v_request.condition, null, null, v_request.id);
  insert into public.profile_change_history (client_id, field_name, old_value, new_value)
  values (auth.uid(), 'Health condition removal requested', v_request.condition, 'Pending Dietitian review');
  perform public.append_audit_event('health_condition_removal.requested', jsonb_build_object(
    'request_id', v_request.id, 'condition', v_request.condition
  ));
  return v_request;
end;
$$;

