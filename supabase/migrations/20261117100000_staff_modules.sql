create or replace function public.order_status_allowed_for_staff(
  p_role public.app_role,
  p_old public.order_status,
  p_new public.order_status
)
returns boolean
language plpgsql
immutable
as $$
begin
  if p_role = 'owner_admin' then
    return true;
  end if;
  if p_role = 'dietitian_staff' then
    -- Decisions go through dietitian_review_order so the reason is recorded (DIT-15 #3).
    return false;
  end if;
  if p_role = 'kitchen_staff' then
    return (p_old, p_new) in (
      ('paid', 'preparing'),
      ('confirmed', 'preparing'),
      ('preparing', 'ready_for_delivery'),
      ('preparing', 'ready_for_pick_up'),
      ('ready_for_pick_up', 'completed')
    );
  end if;
  if p_role = 'delivery_staff' then
    return (p_old, p_new) in (
      ('ready_for_delivery', 'out_for_delivery'),
      ('out_for_delivery', 'completed')
    );
  end if;
  return false;
end;
$$;

create or replace function public.record_order_status_change(
  p_order_id uuid,
  p_new_status public.order_status,
  p_title text default 'Order status changed',
  p_body text default null
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
  v_body text;
begin
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'order_not_found'; end if;
  if not public.validate_order_status_transition(v_order.fulfillment_type, v_order.status, p_new_status) then
    raise exception 'invalid_status_transition';
  end if;
  update public.orders
  set status = p_new_status, updated_at = now()
  where id = p_order_id
  returning * into v_order;
  insert into public.order_status_history (order_id, status, changed_by)
  values (p_order_id, p_new_status, auth.uid());
  v_body := coalesce(
    p_body,
    'Your order ' || v_order.tracking_number || ' is now ' || public.order_status_label(p_new_status) || '.'
  );
  insert into public.notifications (client_id, title, body, notification_type, order_id)
  values (v_order.client_id, p_title, v_body, 'status_changed', p_order_id);
  perform public.append_audit_event(
    'order_status_changed',
    jsonb_build_object('order_id', p_order_id, 'order_no', v_order.order_no, 'status', p_new_status)
  );
  return v_order;
end;
$$;
-- Internal only: callers must go through role-checked RPCs.
revoke all on function public.record_order_status_change(uuid, public.order_status, text, text) from public, anon, authenticated;

create or replace function public.transition_order_status(
  p_order_id uuid,
  p_new_status public.order_status
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
  v_role public.app_role;
begin
  v_role := public.require_staff(array['owner_admin', 'dietitian_staff', 'kitchen_staff', 'delivery_staff']::public.app_role[]);
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'order_not_found'; end if;
  if v_role = 'delivery_staff' and v_order.assigned_delivery_id is distinct from auth.uid() then
    raise exception 'not_assigned';
  end if;
  if not public.order_status_allowed_for_staff(v_role, v_order.status, p_new_status) then
    raise exception 'role_cannot_transition';
  end if;
  if not public.validate_order_status_transition(v_order.fulfillment_type, v_order.status, p_new_status) then
    raise exception 'invalid_status_transition';
  end if;
  return public.record_order_status_change(p_order_id, p_new_status);
end;
$$;
grant execute on function public.transition_order_status(uuid, public.order_status) to authenticated;

-- Staff bells follow the order lifecycle (meal-service-modules.md).
create or replace function public.orders_notify_staff()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_no text := public.order_display_no(new.order_no);
begin
  if tg_op = 'INSERT' then
    if new.status = 'for_dietitian_review' then
      perform public.notify_staff('dietitian_staff', 'reviewRequest',
        'Order ' || v_no || ' needs review', 'A new order was submitted for Dietitian review.', new.id);
      perform public.notify_staff('owner_admin', 'newOrder',
        'New order ' || v_no, 'Waiting for Dietitian review.', new.id);
    end if;
    return new;
  end if;
  if new.status is distinct from old.status then
    if new.status = 'paid' then
      perform public.notify_staff('kitchen_staff', 'newOrder',
        'New order ' || v_no, 'Approved and paid. Ready to prepare.', new.id);
      perform public.notify_staff('owner_admin', 'orderPaid', 'Order ' || v_no || ' was paid', '', new.id);
    elsif new.status = 'ready_for_delivery' then
      perform public.notify_staff('owner_admin', 'readyForPickup',
        'Order ' || v_no || ' is ready for pickup',
        case when new.assigned_delivery_id is null then 'Assign a delivery staff member.' else '' end, new.id);
      if new.assigned_delivery_id is not null then
        perform public.notify_staff('delivery_staff', 'readyForPickup',
          'Order ' || v_no || ' is ready for pickup', 'Collect the order and start the delivery.', new.id,
          new.assigned_delivery_id);
      end if;
    elsif new.status = 'ready_for_pick_up' then
      perform public.notify_staff('owner_admin', 'readyForPickup',
        'Order ' || v_no || ' is ready for customer pickup', '', new.id);
    elsif new.status = 'completed' then
      perform public.notify_staff('owner_admin', 'orderCompleted', 'Order ' || v_no || ' was completed', '', new.id);
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists orders_notify_staff_insert on public.orders;
create trigger orders_notify_staff_insert
  after insert on public.orders
  for each row execute procedure public.orders_notify_staff();
drop trigger if exists orders_notify_staff_update on public.orders;
create trigger orders_notify_staff_update
  after update of status on public.orders
  for each row execute procedure public.orders_notify_staff();

-- ADM-12 B: assign a delivery order to Delivery Staff (only Delivery-role staff can be picked).
create or replace function public.assign_delivery_staff(p_order_id uuid, p_staff_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
  v_staff public.profiles;
begin
  perform public.require_staff(array['owner_admin']::public.app_role[]);
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'order_not_found'; end if;
  if v_order.fulfillment_type <> 'delivery' then raise exception 'pickup_order_not_assignable'; end if;
  if v_order.status in ('completed', 'cancelled') then raise exception 'order_closed'; end if;
  select * into v_staff from public.profiles where id = p_staff_id and role = 'delivery_staff' and is_active;
  if not found then raise exception 'not_delivery_staff'; end if;
  update public.orders
  set assigned_delivery_id = p_staff_id, assigned_at = now(), updated_at = now()
  where id = p_order_id
  returning * into v_order;
  perform public.notify_staff('delivery_staff', 'readyForPickup',
    'Order ' || public.order_display_no(v_order.order_no) || ' was assigned to you',
    case when v_order.status = 'ready_for_delivery' then 'Collect the order and start the delivery.'
         else 'You will be notified when it is ready for pickup.' end,
    v_order.id, p_staff_id);
  perform public.append_audit_event('order_assigned', jsonb_build_object(
    'order_id', v_order.id, 'order_no', v_order.order_no,
    'assignee_id', p_staff_id, 'assignee_name', trim(v_staff.first_name || ' ' || v_staff.last_name)
  ));
  return v_order;
end;
$$;

-- DIT-15: approve (→ payment) or return with a reason. Returned orders are closed as Cancelled
-- because USR-21 has no "returned" stage; the user is told why and re-orders (recorded conflict).
create or replace function public.dietitian_review_order(
  p_order_id uuid,
  p_approve boolean,
  p_reason text default null
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
  v_reason text := nullif(trim(coalesce(p_reason, '')), '');
begin
  perform public.require_staff(array['dietitian_staff', 'owner_admin']::public.app_role[]);
  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'order_not_found'; end if;
  if v_order.status <> 'for_dietitian_review' then raise exception 'already_reviewed'; end if;
  if not p_approve and v_reason is null then raise exception 'reason_required'; end if;
  update public.orders
  set review_decision = case when p_approve then 'approved' else 'returned' end,
      review_reason = v_reason,
      reviewed_by = auth.uid(),
      reviewed_at = now()
  where id = p_order_id;
  if p_approve then
    v_order := public.record_order_status_change(
      p_order_id, 'awaiting_payment', 'Order approved',
      'Your order ' || v_order.tracking_number || ' was approved by the Dietitian. You can now pay for it.'
    );
  else
    v_order := public.record_order_status_change(
      p_order_id, 'cancelled', 'Order returned for changes',
      'The Dietitian returned your order ' || v_order.tracking_number || ': ' || v_reason ||
      ' Please revise your meals and submit a new order.'
    );
  end if;
  perform public.append_audit_event('order_reviewed', jsonb_build_object(
    'order_id', p_order_id, 'order_no', v_order.order_no,
    'decision', case when p_approve then 'approved' else 'returned' end, 'reason', v_reason
  ));
  return v_order;
end;
$$;

