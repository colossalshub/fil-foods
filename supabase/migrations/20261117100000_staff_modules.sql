-- ADM-21: only the Admin changes which notifications Kitchen / Delivery receive; logged (ADM-20).
create or replace function public.save_staff_notification_settings(
  p_role text,
  p_enabled boolean,
  p_types jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_settings jsonb;
  v_old jsonb;
  v_new jsonb;
  v_enabled boolean;
begin
  perform public.require_staff(array['owner_admin']::public.app_role[]);
  if p_role not in ('kitchen', 'delivery') then raise exception 'invalid_role'; end if;
  select value into v_settings from public.settings where key = 'staff_notifications' for update;
  v_settings := coalesce(v_settings, '{}'::jsonb);
  v_old := coalesce(v_settings -> p_role, '{}'::jsonb);
  -- Every type OFF counts as notifications OFF for that role.
  v_enabled := p_enabled and exists (
    select 1 from jsonb_each_text(coalesce(p_types, '{}'::jsonb)) t where t.value = 'true'
  );
  v_new := jsonb_build_object('enabled', v_enabled, 'types', coalesce(p_types, '{}'::jsonb));
  v_settings := jsonb_set(v_settings, array[p_role], v_new, true);
  insert into public.settings (key, value, updated_at) values ('staff_notifications', v_settings, now())
  on conflict (key) do update set value = excluded.value, updated_at = now();
  perform public.append_audit_event('staff_notifications.updated', jsonb_build_object(
    'role', p_role, 'setting', 'notifications', 'old_value', v_old, 'new_value', v_new
  ));
  return v_settings;
end;
$$;

