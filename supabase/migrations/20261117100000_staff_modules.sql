create or replace function public.decide_health_condition_removal(p_id uuid, p_approve boolean, p_reason text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.health_condition_removal_requests;
  v_reason text := nullif(trim(coalesce(p_reason, '')), '');
  v_info jsonb;
  v_name text;
  v_before text;
  v_after text;
begin
  perform public.require_staff(array['dietitian_staff']::public.app_role[]);
  select * into v_request from public.health_condition_removal_requests where id = p_id for update;
  if not found then raise exception 'request_not_found'; end if;
  if v_request.status <> 'pending' then
    raise exception 'already_decided' using hint = 'This request has already been decided.';
  end if;
  if not p_approve and v_reason is null then
    raise exception 'reason_required' using hint = 'Please enter a reason for rejecting this request.';
  end if;
  v_info := public.removal_request_json(v_request, false);
  v_name := v_info ->> 'recipient_name';

  select string_agg(value, ', ' order by value) into v_before
  from public.client_health_items where client_id = v_request.client_id and item_type = 'condition';

  update public.health_condition_removal_requests
  set status = case when p_approve then 'approved' else 'rejected' end,
      decision_reason = v_reason, decided_by = auth.uid(), decided_at = now()
  where id = p_id
  returning * into v_request;

  if p_approve then
    delete from public.client_health_items
    where client_id = v_request.client_id and item_type = 'condition'
      and lower(value) = lower(v_request.condition);
    perform set_config('app.privileged_profile_write', 'on', true);
    update public.profiles set updated_at = now() where id = v_request.client_id;
    perform set_config('app.privileged_profile_write', 'off', true);
    select string_agg(value, ', ' order by value) into v_after
    from public.client_health_items where client_id = v_request.client_id and item_type = 'condition';
    insert into public.profile_change_history (client_id, field_name, old_value, new_value)
    values (v_request.client_id, 'Health conditions', v_before, coalesce(v_after, 'None'));
    insert into public.notifications (client_id, title, body, notification_type)
    values (v_request.client_id, 'Health condition request approved',
      'Your request to remove ' || v_request.condition || ' from ' || v_name || '''s health conditions was approved.',
      'health_request');
  else
    insert into public.profile_change_history (client_id, field_name, old_value, new_value)
    values (v_request.client_id, 'Health condition removal not approved', v_request.condition, v_reason);
    insert into public.notifications (client_id, title, body, notification_type)
    values (v_request.client_id, 'Health condition request not approved',
      'Your request to remove ' || v_request.condition || ' from ' || v_name || '''s health conditions was not approved. ' || v_reason,
      'health_request');
  end if;

  perform public.append_audit_event('health_condition_removal.decided', jsonb_build_object(
    'request_id', v_request.id, 'recipient', v_name, 'condition', v_request.condition,
    'decision', v_request.status, 'reason', v_reason
  ));
  return public.removal_request_json(v_request, false);
end;
$$;

