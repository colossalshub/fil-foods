-- Returns whether a role should receive a notification type right now (ADM-21 B, C).
create or replace function public.staff_notification_enabled(p_role public.app_role, p_kind text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_settings jsonb;
  v_key text;
  v_role jsonb;
begin
  if p_role not in ('kitchen_staff', 'delivery_staff') then return true; end if;
  v_key := case p_role when 'kitchen_staff' then 'kitchen' else 'delivery' end;
  select value into v_settings from public.settings where key = 'staff_notifications';
  v_role := coalesce(v_settings -> v_key, '{}'::jsonb);
  if coalesce((v_role ->> 'enabled')::boolean, true) = false then return false; end if;
  if not (v_role -> 'types' ? p_kind) then return true; end if;
  return coalesce((v_role -> 'types' ->> p_kind)::boolean, false);
end;
$$;

create or replace function public.notify_staff(
  p_role public.app_role,
  p_kind text,
  p_title text,
  p_body text default '',
  p_order_id uuid default null,
  p_recipient uuid default null,
  p_request_id uuid default null
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  if not public.staff_notification_enabled(p_role, p_kind) then return 0; end if;
  insert into public.staff_notifications (recipient_id, kind, title, body, order_id, request_id)
  select p.id, p_kind, p_title, coalesce(p_body, ''), p_order_id, p_request_id
  from public.profiles p
  where p.role = p_role
    and p.is_active
    and (p_recipient is null or p.id = p_recipient);
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;
revoke all on function public.notify_staff(public.app_role, text, text, text, uuid, uuid, uuid) from public, anon, authenticated;

