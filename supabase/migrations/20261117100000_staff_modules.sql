create or replace function public.require_staff(p_roles public.app_role[])
returns public.app_role
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_role public.app_role;
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;
  v_role := public.current_staff_role();
  if v_role is null or not (v_role = any(p_roles)) then
    raise exception 'not_authorized' using hint = 'You do not have access to this page.';
  end if;
  return v_role;
end;
$$;

-- Clients and staff may edit their own name/contact, never their role or account state.
create or replace function public.protect_profile_privileged_columns()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if current_user in ('postgres', 'supabase_admin', 'service_role')
     or coalesce(auth.role(), '') = 'service_role'
     or coalesce(current_setting('app.privileged_profile_write', true), '') = 'on' then
    return new;
  end if;
  if new.role is distinct from old.role
     or new.is_active is distinct from old.is_active
     or new.is_verified is distinct from old.is_verified
     or new.locked_at is distinct from old.locked_at then
    raise exception 'not_authorized' using hint = 'Role and account status can only be changed by an Admin.';
  end if;
  return new;
end;
$$;

